// Same filter as lib.mask for the live spec, on any event table.
function liveMask(t) {
    const C = t.cols, n = C.gi.length, fi = Object.fromEntries(t.fams.map((f, i) => [f, i]));
    const fams = new Set(spec.fams.map(f => fi[f]));
    const m = new Uint8Array(n);
    for (let r = 0; r < n; r++) {
        if (!fams.has(C.fam[r])) continue;
        if (spec.liveOnly && C.fam[r] === fi.RANGE && !C.liveC[r]) continue;
        if (C.upLow52[r] < spec.upLow52Min) continue;
        if (spec.rsMin > 0 && !(C.rs[r] >= spec.rsMin)) continue;
        if (C.dv[r] < spec.dvMin) continue;
        if (spec.dvPctMin > 0 && !(C.dvPct[r] >= spec.dvPctMin)) continue;
        if (C.rawPrice[r] < spec.rawPriceMin) continue;
        if (C.depth52[r] > spec.depth52Max) continue;
        if (C.baseDepth[r] < 0) continue;
        if (spec.regime === 'spy200' && !C.spy200[r]) continue;
        else if (spec.regime === 'spy50' && !C.spy50[r]) continue;
        else if (spec.regime === 'breadth50' && !(C.breadth[r] >= 50)) continue;
        else if (!['spy200', 'spy50', 'breadth50', 'none'].includes(spec.regime)) throw new Error(`regime ${spec.regime} not handled`);
        if (C.adr[r] < 0) continue;
        m[r] = 1;
    }
    return m;
}
const keyOf = (t, r) => `${t.cols.tid[r]}|${t.cols.gi[r]}|${t.cols.fam[r]}`;
function tradesOf(t, ci) {
    const m = liveMask(t), C = t.cols, out = [];
    for (let r = 0; r < C.gi.length; r++) {
        if (!m[r] || Number.isNaN(t.R[ci][r])) continue;
        out.push({
            k: keyOf(t, r), r, year: Number(t.dates[C.gi[r]].slice(0, 4)), fam: t.fams[C.fam[r]], e: C.egi[r], x: t.xgi[ci][r],
            R: t.R[ci][r], ret: t.ret[ci][r], risk: t.risk[ci][r], tid: C.tid[r], rs: C.rs[r],
        });
    }
    return out;
}
function rowsOf(t) { // every setup row of the live mask (triggered or not)
    const m = liveMask(t), out = new Map();
    for (let r = 0; r < t.cols.gi.length; r++) if (m[r]) out.set(keyOf(t, r), r);
    return out;
}
const inYears = (list, ys) => { const s = new Set(ys); return list.filter(x => s.has(x.year)); };
function st(list) {
    const n = list.length;
    if (!n) return { n: 0, win: NaN, avgR: NaN, totR: 0, se: NaN };
    let s = 0, s2 = 0, w = 0;
    for (const x of list) { s += x.R; s2 += x.R * x.R; if (x.R > 0) w++; }
    const avg = s / n, sd = Math.sqrt(Math.max(0, s2 / n - avg * avg));
    return { n, win: w / n * 100, avgR: avg, totR: s, se: sd / Math.sqrt(n) };
}

// Accounts (restudy.mjs conventions: 1% risk, 25% max position, one position per
// ticker, cash-limited, realized equity; entries from 2007).
function rng(seed) { return () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let x = Math.imul(seed ^ seed >>> 15, 1 | seed); x = x + Math.imul(x ^ x >>> 7, 61 | x) ^ x; return ((x ^ x >>> 14) >>> 0) / 4294967296; }; }
const G_LAST = T.dates.length - 1;
const G2007 = yearSpan(2007)[0], G2023 = yearSpan(2023)[0];
const idleRet = idleReturns(RULES.idleCash?.mode ? RULES.idleCash : { mode: 'none' });
function accounts(list) {
    const tr = list.filter(x => x.e >= G2007).map(x => ({ ...x, key: x.rs }));
    const rand = rng(12345), c = [], dd = [];
    for (let i = 0; i < 40; i++) { const p = simulatePortfolio(tr.map(x => ({ ...x, key: rand() }))); c.push(p.cagr); dd.push(p.maxDD); }
    c.sort((a, b) => a - b); dd.sort((a, b) => a - b);
    const q = (a, f) => a[Math.floor(f * (a.length - 1))];
    const rsCash = simulatePortfolio(tr);
    const rsSpy = simulatePortfolio(tr, { idleRet, span: [G2007, G_LAST] });
    const rsSpyOpt = simulatePortfolio(tr, { idleRet, span: [G2007, G_LAST], preFill: true });
    const tr23 = tr.filter(x => x.e >= G2023);
    const r23Cash = simulatePortfolio(tr23, { span: [G2023, G_LAST] });
    const r23Spy = simulatePortfolio(tr23, { idleRet, span: [G2023, G_LAST] });
    return {
        mc: { p10: q(c, 0.1), med: q(c, 0.5), p90: q(c, 0.9), dd: q(dd, 0.5) },
        rsCash: { cagr: rsCash.cagr, dd: rsCash.maxDD, taken: rsCash.taken, yr: rsCash.yr },
        rsSpy: { cagr: rsSpy.cagr, dd: rsSpy.maxDD, yr: rsSpy.yr },
        rsSpyOpt: { cagr: rsSpyOpt.cagr, dd: rsSpyOpt.maxDD },
        r23Cash: { cagr: r23Cash.cagr, dd: r23Cash.maxDD }, r23Spy: { cagr: r23Spy.cagr, dd: r23Spy.maxDD },
    };
}

