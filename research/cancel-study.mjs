// Cancel-pending-buy-stop study (2026-10-15).
//
//   node --max-old-space-size=12000 research/cancel-study.mjs [--rebuild]
//
// Candidate rule: cancel a pending (not yet triggered) buy stop when, after the
// setup day s and before the trigger bar, the stock CLOSES
//   A   below the setup-day structural stop (cd.structStop)
//   Ar  below the ratcheted structural stop (non-RANGE: min(structStop, 0.995 x lows
//       of s+1..m-1), the same ratchet build-events.mjs uses for the trade stop)
//   B   below its 50-day SMA
//   C   A or B          Cr  Ar or B
//   D   more than 10% below the pivot
// No look-ahead: at bar m the trigger (high > pivot, intraday) is checked first;
// the close of bar m can only cancel the order for bars m+1.. . So a fill on bar m
// counts only if no cancelling close occurred on bars s+1..m-1.
//
// Method: build-events.mjs is loaded as text, patched (cancel check inside the
// buy-stop loop; only the live stop|exit combo; output path), written to
// research/data/cancel/ and run once per variant. Everything else (detection,
// features, the 5-session new-setup rule and the 10-session no-retrigger rule,
// trade simulation, costs) is the research builder itself. A cancelled setup sets
// no trigger, so (as live) a later setup of the same family may become eligible.
// The regenerated baseline ('none') must reproduce events.bin exactly.
// Analysis uses research/lib.mjs (mask, yearly, summarize, simulatePortfolio,
// idleReturns) and the restudy.mjs account conventions.
